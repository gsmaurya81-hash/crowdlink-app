# ------------------------------------------------------------------------------
# Logging
#   logs/sync.log       - Shopify / Square sync detail (per store)
#   logs/sync_cron.log  - one START / FINISHED record per nightly cron run
#                         (shows which DATABASE the cron really used)
#   logs/app.log        - audit trail of user actions + every unhandled 500 error
# All files rotate (5 MB x 5) so they can never fill the disk.
# ------------------------------------------------------------------------------
LOG_DIR = BASE_DIR / 'logs'
try:
    os.makedirs(str(LOG_DIR), exist_ok=True)   # a fresh deploy must not crash on a missing folder
except OSError:
    pass

# Same as Django's default, stated explicitly: silences models.W042 in the cron
# output WITHOUT creating any migration (BigAutoField would alter every table).
DEFAULT_AUTO_FIELD = 'django.db.models.AutoField'


def _rotating(filename, level='INFO'):
    return {
        'level': level,
        'class': 'logging.handlers.RotatingFileHandler',
        'filename': str(LOG_DIR / filename),
        'maxBytes': 5 * 1024 * 1024,
        'backupCount': 5,
        'formatter': 'verbose',
        'encoding': 'utf-8',
    }


