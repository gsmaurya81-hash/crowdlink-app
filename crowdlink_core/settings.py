# Persistent, cross-process cache — used to store the short-lived Shopify/
# Square OAuth "state" token between the /connect/ redirect and the
# /callback/ request. The Django default (LocMemCache) is per-process and
# NOT shared, so on a multi-worker/Passenger host the callback often lands
# on a different worker than the one that issued the state token, causing
# "Invalid, expired, or missing state token (CSRF attempt)" even on a valid,
# fast OAuth flow. A file-based cache is shared by every worker (they all
# read/write the same folder on disk) and needs no DB table or migration —
# Django creates the folder itself on first write if it doesn't exist yet.
CACHES = {
    'default': {
        'BACKEND': 'django.core.cache.backends.filebased.FileBasedCache',
        'LOCATION': BASE_DIR / 'django_cache',
    }
}


